/**
 * Client-side .docx support — works without the Rust backend.
 *
 *  - renderDocxPreview(bytes, container, options): high-fidelity read-only
 *    preview through the vendored docx-preview library (window.docx).
 *  - docxToModel(bytes) -> { model, warnings }: .docx -> word model (the
 *    frozen WORD CONTRACT in src/office-backend/src/model.rs), mirroring the
 *    backend reader: paragraphs, headings by style, run formatting, hyperlinks
 *    (relationship and field based), numbering lists with levels, tables with
 *    gridSpan, images as data: URLs, page breaks; warnings for dropped parts.
 *    Also meta.page (last sectPr), meta.title/author/subject (core.xml) and
 *    meta.header / meta.footer (default header/footer of the last section,
 *    one paragraph; PAGE / NUMPAGES fields become "{PAGE}" / "{NUMPAGES}").
 *  - modelToDocx(model) -> Uint8Array: word model -> a complete .docx package
 *    (content types, rels, styles.xml with Heading1-6/Quote/Code/Hyperlink/
 *    ListParagraph/TableGrid/Header/Footer, numbering.xml with real bullet and
 *    numbered lists, media, settings, core properties, header1.xml /
 *    footer1.xml with real page-number fields, sectPr).
 *
 * Needs the global JSZip (vendor/jszip.min.js). XML is parsed with a small
 * built-in parser (OOXML parts are plain, well-formed XML), so the reader also
 * runs in workers and under Node for tests; element/attribute names are
 * matched by local name, independent of namespace prefixes.
 */

export function docxPreviewAvailable() {
  return typeof docx !== "undefined" && !!docx && typeof docx.renderAsync === "function";
}

/**
 * Render a .docx (bytes) into a container element with docx-preview.
 * Styles generated by docx-preview are placed inside the (attached) container
 * itself, so they apply and are removed together with the preview.
 */
export async function renderDocxPreview(bytes, container, options = {}) {
  if (!docxPreviewAvailable()) throw new Error("docx-preview library not loaded");
  const data = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  const body = (container.querySelector && container.querySelector(".docx-body")) || container;
  // styleContainer null => docx-preview appends its <style> elements to the
  // body container (which is in the document). A detached element here would
  // silently drop every document style.
  const { styleContainer = null, ...rest } = options;
  await docx.renderAsync(data, body, styleContainer, {
    className: "docx",
    inWrapper: true,
    ignoreWidth: false,
    ignoreHeight: false,
    ignoreFonts: false,
    breakPages: true,
    ignoreLastRenderedPageBreak: true,
    experimental: true,
    renderHeaders: true,
    renderFooters: true,
    renderFootnotes: true,
    renderEndnotes: true,
    useBase64URL: true, // no blob: URLs that would leak on every re-render
    ...rest,
  });
  return true;
}

