const IMAGE_CT = {
  png: "image/png", jpeg: "image/jpeg", gif: "image/gif", bmp: "image/bmp", tiff: "image/tiff",
  emf: "image/x-emf", wmf: "image/x-wmf",
};

/** meta.header / meta.footer -> { runs, align } with some text, or null. */
function headerFooterMeta(v) {
  if (!v || typeof v !== "object" || !Array.isArray(v.runs)) return null;
  const runs = v.runs.filter((r) => r && typeof r === "object" && r.t != null && String(r.t) !== "");
  if (!runs.some((r) => String(r.t).trim())) return null;
  const align = ["center", "right", "justify", "left"].includes(v.align) ? v.align : undefined;
  return { runs, align };
}

/**
 * Write a word model as a .docx package.
 * @returns {Promise<Uint8Array>}
 */
export async function modelToDocx(model) {
  const JSZip = getJSZip();
  const w = new DocxWriter();
  const ps = pageSetupOf(model && model.meta);
  let body = await w.blocksXml((model && model.blocks) || [], ps.textWidth);
  if (!body.endsWith("</w:p>")) body += "<w:p/>"; // empty doc / ends with a table
  // Header / footer parts (meta.header / meta.footer: one paragraph each).
  const hfParts = [];
  let hfRefs = "";
  for (const kind of ["header", "footer"]) {
    const hf = headerFooterMeta(model && model.meta && model.meta[kind]);
    if (!hf) continue;
    const pw = new DocxWriter({ part: true });
    const para = pw.paraXml({ style: kind === "header" ? "Header" : "Footer", align: hf.align, content: pw.runsXml(splitFieldRuns(hf.runs)) });
    const tag = kind === "header" ? "hdr" : "ftr";
    const name = `${kind}1.xml`;
    const xml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:${tag} xmlns:w="${NS.w}" xmlns:r="${NS.r}">${para}</w:${tag}>`;
    const rid = w.addRel(kind, name);
    hfRefs += `<w:${kind}Reference w:type="default" r:id="${rid}"/>`;
    const rels = pw.rels.length
      ? `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="${NS.pkgRel}">` +
        pw.rels.map((r) => `<Relationship Id="${r.id}" Type="${REL}${r.type}" Target="${xmlText(r.target)}"${r.external ? ' TargetMode="External"' : ""}/>`).join("") +
        "</Relationships>"
      : null;
    hfParts.push({ kind, name, xml, rels });
  }
  const sectPr = `<w:sectPr>${hfRefs}<w:pgSz w:w="${ps.w}" w:h="${ps.h}"${ps.landscape ? ' w:orient="landscape"' : ""}/>` +
    `<w:pgMar w:top="${ps.m.top}" w:right="${ps.m.right}" w:bottom="${ps.m.bottom}" w:left="${ps.m.left}" w:header="${ps.m.header}" w:footer="${ps.m.footer}" w:gutter="0"/>` +
    '<w:cols w:space="720"/><w:docGrid w:linePitch="360"/></w:sectPr>';
  const documentXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="${NS.w}" xmlns:r="${NS.r}" xmlns:wp="${NS.wp}" xmlns:a="${NS.a}" xmlns:pic="${NS.pic}">` +
    `<w:body>${body}${sectPr}</w:body></w:document>`;

  const docRels = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="${NS.pkgRel}">` +
    w.rels.map((r) => `<Relationship Id="${r.id}" Type="${REL}${r.type}" Target="${xmlText(r.target)}"${r.external ? ' TargetMode="External"' : ""}/>`).join("") +
    "</Relationships>";

  const pkgRels = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="${NS.pkgRel}">` +
    `<Relationship Id="rId1" Type="${REL}officeDocument" Target="word/document.xml"/>` +
    '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/>' +
    `<Relationship Id="rId3" Type="${REL}extended-properties" Target="docProps/app.xml"/>` +
    "</Relationships>";

  const ctDefaults = [...w.mediaExts].map((e) => `<Default Extension="${e}" ContentType="${IMAGE_CT[e]}"/>`).join("");
  const contentTypes = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="${NS.ct}">` +
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' +
    '<Default Extension="xml" ContentType="application/xml"/>' + ctDefaults +
    '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>' +
    '<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>' +
    '<Override PartName="/word/numbering.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.numbering+xml"/>' +
    '<Override PartName="/word/settings.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.settings+xml"/>' +
    hfParts.map((h) => `<Override PartName="/word/${h.name}" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.${h.kind}+xml"/>`).join("") +
    '<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>' +
    '<Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/>' +
    "</Types>";

  const now = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
  const meta = (model && model.meta) || {};
  const prop = (key, tag) => (typeof meta[key] === "string" && meta[key].trim() ? `<${tag}>${xmlText(meta[key].trim())}</${tag}>` : "");
  const title = prop("title", "dc:title") + prop("subject", "dc:subject") + prop("author", "dc:creator") + prop("author", "cp:lastModifiedBy");
  const core = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" xmlns:dcmitype="http://purl.org/dc/dcmitype/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">` +
    `${title}<dcterms:created xsi:type="dcterms:W3CDTF">${now}</dcterms:created><dcterms:modified xsi:type="dcterms:W3CDTF">${now}</dcterms:modified></cp:coreProperties>`;
  const app = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes"><Application>Office Viewer</Application></Properties>`;

  const zip = new JSZip();
  zip.file("[Content_Types].xml", contentTypes);
  zip.file("_rels/.rels", pkgRels);
  zip.file("docProps/core.xml", core);
  zip.file("docProps/app.xml", app);
  zip.file("word/document.xml", documentXml);
  zip.file("word/_rels/document.xml.rels", docRels);
  zip.file("word/styles.xml", STYLES_XML);
  zip.file("word/numbering.xml", numberingXml(w.nums));
  zip.file("word/settings.xml", SETTINGS_XML);
  for (const h of hfParts) {
    zip.file(`word/${h.name}`, h.xml);
    if (h.rels) zip.file(`word/_rels/${h.name}.rels`, h.rels);
  }
  for (const m of w.media) zip.file(m.path, m.bytes);
  return zip.generateAsync({ type: "uint8array", compression: "DEFLATE", compressionOptions: { level: 6 } });
}
