const ENTITY = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };

function decodeEntities(s) {
  if (s.indexOf("&") < 0) return s;
  return s.replace(/&(#x[0-9a-fA-F]+|#\d+|amp|lt|gt|quot|apos);/g, (m, e) => {
    if (e[0] === "#") {
      const cp = e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      try { return String.fromCodePoint(cp); } catch { return m; }
    }
    return ENTITY[e];
  });
}

function localOf(name) {
  const i = name.indexOf(":");
  return i < 0 ? name : name.slice(i + 1);
}

const ATTR_RE = /\s*([^\s=/>]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/y;
const NAME_RE = /[^\s/>]+/y;

/**
 * Parse XML text into a light tree: element = { name, local, attrs, children },
 * text = { text }. Comments, PIs and DOCTYPE are skipped (no entity expansion).
 */
export function parseXml(text) {
  const root = { name: "#document", local: "#document", attrs: {}, children: [] };
  const stack = [root];
  const n = text.length;
  let i = text.charCodeAt(0) === 0xfeff ? 1 : 0;
  const addText = (s) => {
    if (s) stack[stack.length - 1].children.push({ text: s });
  };
  while (i < n) {
    const lt = text.indexOf("<", i);
    if (lt < 0) {
      addText(decodeEntities(text.slice(i)));
      break;
    }
    if (lt > i) addText(decodeEntities(text.slice(i, lt)));
    if (text.startsWith("<!--", lt)) {
      const e = text.indexOf("-->", lt + 4);
      i = e < 0 ? n : e + 3;
      continue;
    }
    if (text.startsWith("<![CDATA[", lt)) {
      const e = text.indexOf("]]>", lt + 9);
      addText(text.slice(lt + 9, e < 0 ? n : e));
      i = e < 0 ? n : e + 3;
      continue;
    }
    if (text.startsWith("<?", lt)) {
      const e = text.indexOf("?>", lt + 2);
      i = e < 0 ? n : e + 2;
      continue;
    }
    if (text.startsWith("<!", lt)) {
      // DOCTYPE (possibly with an internal subset): skip it entirely.
      let depth = 0;
      let j = lt + 2;
      for (; j < n; j++) {
        const c = text[j];
        if (c === "[") depth++;
        else if (c === "]") depth--;
        else if (c === ">" && depth <= 0) break;
      }
      i = j + 1;
      continue;
    }
    if (text[lt + 1] === "/") {
      const e = text.indexOf(">", lt);
      const name = text.slice(lt + 2, e < 0 ? n : e).trim();
      // Tolerant close: pop up to the matching element.
      for (let k = stack.length - 1; k > 0; k--) {
        if (stack[k].name === name) {
          stack.length = k;
          break;
        }
      }
      i = e < 0 ? n : e + 1;
      continue;
    }
    NAME_RE.lastIndex = lt + 1;
    const nm = NAME_RE.exec(text);
    if (!nm) {
      addText("<");
      i = lt + 1;
      continue;
    }
    const el = { name: nm[0], local: localOf(nm[0]), attrs: {}, children: [] };
    let j = NAME_RE.lastIndex;
    for (;;) {
      ATTR_RE.lastIndex = j;
      const am = ATTR_RE.exec(text);
      if (!am) break;
      el.attrs[am[1]] = decodeEntities(am[2] !== undefined ? am[2] : am[3]);
      j = ATTR_RE.lastIndex;
    }
    const close = text.indexOf(">", j);
    if (close < 0) break;
    const selfClosing = text[close - 1] === "/";
    stack[stack.length - 1].children.push(el);
    if (!selfClosing) stack.push(el);
    i = close + 1;
  }
  return root;
}

function kids(node, local) {
  const out = [];
  if (!node || !node.children) return out;
  for (const c of node.children) if (c.local && (!local || c.local === local)) out.push(c);
  return out;
}

function kid(node, local) {
  if (!node || !node.children) return null;
  for (const c of node.children) if (c.local === local) return c;
  return null;
}

function findDesc(node, local) {
  if (!node || !node.children) return null;
  for (const c of node.children) {
    if (!c.local) continue;
    if (c.local === local) return c;
    const d = findDesc(c, local);
    if (d) return d;
  }
  return null;
}

function findAllDesc(node, local, out = []) {
  if (!node || !node.children) return out;
  for (const c of node.children) {
    if (!c.local) continue;
    if (c.local === local) out.push(c);
    else findAllDesc(c, local, out);
  }
  return out;
}

/** Attribute by qualified name, falling back to local name ("r:id" -> any "*:id"). */
function attr(node, name) {
  if (!node) return null;
  const a = node.attrs;
  if (name in a) return a[name];
  const want = localOf(name);
  for (const k in a) if (localOf(k) === want) return a[k];
  return null;
}

function textOf(node) {
  if (!node) return "";
  if (node.text !== undefined) return node.text;
  let s = "";
  for (const c of node.children) s += textOf(c);
  return s;
}

function decodeXmlBytes(u8) {
  if (u8.length >= 2 && u8[0] === 0xff && u8[1] === 0xfe) return new TextDecoder("utf-16le").decode(u8.subarray(2));
  if (u8.length >= 2 && u8[0] === 0xfe && u8[1] === 0xff) return new TextDecoder("utf-16be").decode(u8.subarray(2));
  return new TextDecoder("utf-8").decode(u8);
}

