/** Pixel size from image bytes (PNG, GIF, JPEG, BMP), or null. */
export function imageSize(u8) {
  try {
    if (u8.length > 24 && u8[0] === 0x89 && u8[1] === 0x50 && u8[2] === 0x4e && u8[3] === 0x47) {
      const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
      return { w: dv.getUint32(16), h: dv.getUint32(20) };
    }
    if (u8.length > 10 && u8[0] === 0x47 && u8[1] === 0x49 && u8[2] === 0x46) {
      return { w: u8[6] | (u8[7] << 8), h: u8[8] | (u8[9] << 8) };
    }
    if (u8.length > 26 && u8[0] === 0x42 && u8[1] === 0x4d) {
      const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
      return { w: Math.abs(dv.getInt32(18, true)), h: Math.abs(dv.getInt32(22, true)) };
    }
    if (u8.length > 4 && u8[0] === 0xff && u8[1] === 0xd8) {
      let p = 2;
      while (p + 9 < u8.length) {
        if (u8[p] !== 0xff) { p++; continue; }
        const marker = u8[p + 1];
        if (marker === 0xff) { p++; continue; }
        if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { p += 2; continue; }
        const len = (u8[p + 2] << 8) | u8[p + 3];
        if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
          return { h: (u8[p + 5] << 8) | u8[p + 6], w: (u8[p + 7] << 8) | u8[p + 8] };
        }
        p += 2 + len;
      }
    }
  } catch {
    // fall through
  }
  return null;
}

/** Defensive limits for untrusted archives (zip bombs, absurd entry counts). */
function checkZipLimits(zip) {
  const names = Object.keys(zip.files);
  if (names.length > 20000) throw new Error("This document contains too many parts to open safely.");
  let total = 0;
  for (const name of names) {
    const f = zip.files[name];
    const d = f && f._data;
    if (!d || typeof d.uncompressedSize !== "number") continue;
    total += d.uncompressedSize;
    if (d.uncompressedSize > 512 * 1024 * 1024) throw new Error(`Part ${name} is too large to open safely.`);
    if (d.compressedSize > 0 && d.uncompressedSize > 64 * 1024 * 1024 && d.uncompressedSize / d.compressedSize > 1000) {
      throw new Error("This document looks like a ZIP bomb and was not opened.");
    }
  }
  if (total > 1024 * 1024 * 1024) throw new Error("This document is too large to open safely (over 1 GB uncompressed).");
}

function resolvePart(baseDir, target) {
  let t = String(target || "").replace(/\\/g, "/");
  try { t = decodeURIComponent(t); } catch { /* keep literal */ }
  const parts = (t.startsWith("/") ? t.slice(1) : baseDir + t).split("/");
  const out = [];
  for (const p of parts) {
    if (p === "" || p === ".") continue;
    if (p === "..") out.pop();
    else out.push(p);
  }
  return out.join("/");
}

function parseRels(xml) {
  const map = new Map();
  if (!xml) return map;
  for (const r of findAllDesc(parseXml(xml), "Relationship")) {
    const id = attr(r, "Id");
    if (!id) continue;
    map.set(id, {
      target: attr(r, "Target") || "",
      type: attr(r, "Type") || "",
      external: /^external$/i.test(attr(r, "TargetMode") || ""),
    });
  }
  return map;
}

