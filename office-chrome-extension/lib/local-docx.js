/** Word's named highlight colours. */
const HIGHLIGHT_HEX = {
  yellow: "#FFFF00", green: "#00FF00", cyan: "#00FFFF", magenta: "#FF00FF", blue: "#0000FF",
  red: "#FF0000", darkBlue: "#00008B", darkCyan: "#008B8B", darkGreen: "#006400",
  darkMagenta: "#800080", darkRed: "#8B0000", darkYellow: "#808000", darkGray: "#A9A9A9",
  lightGray: "#D3D3D3", black: "#000000", white: "#FFFFFF",
};

function onOff(el) {
  const v = attr(el, "val");
  return !(v === "0" || v === "false" || v === "off");
}

function hexOf(v) {
  return v && /^[0-9a-f]{6}$/i.test(v) ? `#${v.toUpperCase()}` : null;
}

/** w:rPr -> marks; false/null values mean "explicitly off" so they can override a style. */
function rPrMarks(rPr) {
  const m = {};
  if (!rPr) return m;
  let hlFromHighlight = false;
  for (const c of kids(rPr)) {
    switch (c.local) {
      case "rStyle": m.rStyle = attr(c, "val"); break;
      case "b": m.b = onOff(c); break;
      case "i": m.i = onOff(c); break;
      case "strike": case "dstrike": m.s = onOff(c); break;
      case "u": {
        const v = attr(c, "val");
        m.u = v ? v !== "none" : true;
        break;
      }
      case "vertAlign": {
        const v = attr(c, "val");
        m.sup = v === "superscript";
        m.sub = v === "subscript";
        break;
      }
      case "color": m.color = hexOf(attr(c, "val")); break;
      case "sz": {
        const v = parseInt(attr(c, "val") || "", 10);
        if (v > 0) m.size = v / 2;
        break;
      }
      case "rFonts": {
        const f = attr(c, "ascii") || attr(c, "hAnsi") || attr(c, "cs") || attr(c, "eastAsia");
        if (f) m.font = f;
        break;
      }
      case "highlight": {
        const v = attr(c, "val");
        m.hl = v && v !== "none" ? HIGHLIGHT_HEX[v] || null : null;
        hlFromHighlight = true;
        break;
      }
      case "shd": {
        const fill = hexOf(attr(c, "fill"));
        if (!hlFromHighlight && fill && fill !== "#FFFFFF") m.hl = fill;
        break;
      }
      case "vanish": case "specVanish": m.vanish = onOff(c); break;
      default: break;
    }
  }
  return m;
}

function parseStyles(xml) {
  const styles = new Map();
  let defaultPara = null;
  if (!xml) return { styles, defaultPara };
  for (const s of findAllDesc(parseXml(xml), "style")) {
    const id = attr(s, "styleId");
    if (!id) continue;
    const pPr = kid(s, "pPr");
    const numPr = pPr && kid(pPr, "numPr");
    const st = {
      id,
      type: attr(s, "type") || "paragraph",
      name: (attr(kid(s, "name"), "val") || "").toLowerCase(),
      basedOn: attr(kid(s, "basedOn"), "val"),
      outline: pPr && kid(pPr, "outlineLvl") ? parseInt(attr(kid(pPr, "outlineLvl"), "val"), 10) : null,
      numId: numPr && kid(numPr, "numId") ? attr(kid(numPr, "numId"), "val") : null,
      ilvl: numPr && kid(numPr, "ilvl") ? parseInt(attr(kid(numPr, "ilvl"), "val"), 10) || 0 : null,
      jc: pPr && kid(pPr, "jc") ? attr(kid(pPr, "jc"), "val") : null,
      pageBreakBefore: !!(pPr && kid(pPr, "pageBreakBefore") && onOff(kid(pPr, "pageBreakBefore"))),
      marks: rPrMarks(kid(s, "rPr")),
    };
    styles.set(id, st);
    const def = attr(s, "default");
    if (st.type === "paragraph" && (def === "1" || def === "true")) defaultPara = id;
  }
  if (!defaultPara) {
    // Some writers omit w:default; "Normal" is the conventional base style.
    for (const st of styles.values()) {
      if (st.type === "paragraph" && (st.name === "normal" || st.id === "Normal")) { defaultPara = st.id; break; }
    }
  }
  return { styles, defaultPara };
}

/** Block kind implied by a single style's name/id (no inheritance). */
function kindOfStyle(st) {
  const names = [st.name, st.id.toLowerCase()];
  for (const n of names) {
    const h = /^heading\s*([1-9])$/.exec(n);
    if (h) return `h${Math.min(6, parseInt(h[1], 10))}`;
  }
  for (const n of names) {
    if (n === "title") return "h1";
    if (n === "subtitle") return "h2";
    if (/quote/.test(n)) return "quote";
    if (/(^|\s)(code|source code|html preformatted|preformatted|macro|macro text|plain text)$/.test(n) || /^(code|sourcecode|htmlpreformatted|macrotext|plaintext)$/.test(n)) return "code";
  }
  return null;
}

/** Resolve a style with its basedOn chain. */
function resolveStyle(ctx, id) {
  const cache = ctx.styleCache;
  if (!id) return { kind: null, outline: null, numId: null, ilvl: null, jc: null, pageBreakBefore: false, marks: {} };
  if (cache.has(id)) return cache.get(id);
  const chain = [];
  const seen = new Set();
  // A style id used in the document but not defined in styles.xml (some
  // generators omit styles.xml entirely): infer what we can from the id.
  let cur = ctx.styles.styles.get(id) || {
    id, type: "paragraph", name: id.toLowerCase(), basedOn: null, outline: null, numId: null, ilvl: null,
    jc: null, pageBreakBefore: false,
    marks: /^strong$/i.test(id) ? { b: true } : /^emphasis$/i.test(id) ? { i: true } : {},
  };
  while (cur && !seen.has(cur.id) && chain.length < 32) {
    seen.add(cur.id);
    chain.push(cur);
    cur = cur.basedOn ? ctx.styles.styles.get(cur.basedOn) : null;
  }
  const r = { kind: null, outline: null, numId: null, ilvl: null, jc: null, pageBreakBefore: false, marks: {} };
  for (const st of chain) {
    if (!r.kind) r.kind = kindOfStyle(st);
    if (r.outline == null && st.outline != null && !Number.isNaN(st.outline)) r.outline = st.outline;
    if (r.numId == null && st.numId != null) r.numId = st.numId;
    if (r.ilvl == null && st.ilvl != null) r.ilvl = st.ilvl;
    if (r.jc == null && st.jc != null) r.jc = st.jc;
    if (st.pageBreakBefore) r.pageBreakBefore = true;
  }
  // Run formatting inherited from the default paragraph style (Normal) is the
  // document baseline, not formatting of this paragraph.
  for (let k = chain.length - 1; k >= 0; k--) {
    if (chain[k].id !== ctx.styles.defaultPara) Object.assign(r.marks, chain[k].marks);
  }
  if (!r.kind && r.outline != null && r.outline >= 0 && r.outline <= 5) r.kind = `h${r.outline + 1}`;
  // "List Bullet 2" / "ListNumber" styles without numbering info still mean a list.
  for (const st of chain) {
    const m = /^list ?(bullet|number) ?([1-9])?$/.exec(st.name) || /^list(bullet|number)([1-9])?$/.exec(st.id.toLowerCase());
    if (m) {
      r.listHint = { list: m[1] === "bullet" ? "ul" : "ol", level: m[2] ? parseInt(m[2], 10) - 1 : 0 };
      break;
    }
  }
  cache.set(id, r);
  return r;
}

function parseNumbering(xml, stylesInfo) {
  const abstracts = new Map(); // absId -> { levels: Map(ilvl -> fmt), styleLink }
  const nums = new Map(); // numId -> { abs, overrides: Map(ilvl -> fmt) }
  if (!xml) return { abstracts, nums };
  const doc = parseXml(xml);
  const lvlFmt = (lvl) => attr(kid(lvl, "numFmt"), "val") || "decimal";
  for (const a of findAllDesc(doc, "abstractNum")) {
    const levels = new Map();
    for (const lvl of kids(a, "lvl")) levels.set(parseInt(attr(lvl, "ilvl"), 10) || 0, lvlFmt(lvl));
    abstracts.set(attr(a, "abstractNumId"), { levels, styleLink: attr(kid(a, "numStyleLink"), "val") });
  }
  for (const nm of findAllDesc(doc, "num")) {
    const overrides = new Map();
    for (const o of kids(nm, "lvlOverride")) {
      const lvl = kid(o, "lvl");
      if (lvl) overrides.set(parseInt(attr(o, "ilvl"), 10) || 0, lvlFmt(lvl));
    }
    nums.set(attr(nm, "numId"), { abs: attr(kid(nm, "abstractNumId"), "val"), overrides });
  }
  // numStyleLink: the abstract's levels live in another abstract, reached via a numbering style.
  for (const a of abstracts.values()) {
    if (a.levels.size || !a.styleLink || !stylesInfo) continue;
    const st = stylesInfo.styles.get(a.styleLink);
    const linked = st && st.numId && nums.get(st.numId);
    const target = linked && abstracts.get(linked.abs);
    if (target && target !== a) a.levels = target.levels;
  }
  return { abstracts, nums };
}

/** "ul" | "ol" | null (numbering removed / no visible marker). */
function listKindOf(ctx, numId, ilvl) {
  if (numId == null || numId === "0") return null;
  const num = ctx.numbering.nums.get(String(numId));
  if (!num) return "ul";
  let fmt = num.overrides.get(ilvl);
  if (!fmt) {
    const abs = ctx.numbering.abstracts.get(num.abs);
    fmt = abs ? abs.levels.get(ilvl) || abs.levels.get(0) : null;
  }
  if (!fmt) return "ul";
  if (fmt === "none") return null;
  return fmt === "bullet" ? "ul" : "ol";
}

function alignOfJc(jc) {
  switch (jc) {
    case "center": return "center";
    case "right": case "end": return "right";
    case "both": case "distribute": case "mediumKashida": case "highKashida": case "lowKashida": case "thaiDistribute": return "justify";
    default: return undefined;
  }
}

const RUN_KEYS = ["b", "i", "u", "s", "sup", "sub", "color", "size", "font", "link", "hl"];

function cleanRunMarks(m) {
  const out = {};
  for (const k of RUN_KEYS) if (m[k]) out[k] = m[k];
  return out;
}

function pushRunText(runs, text, marks) {
  if (!text) return;
  const last = runs[runs.length - 1];
  if (last && RUN_KEYS.every((k) => (last[k] || undefined) === (marks[k] || undefined))) {
    last.t += text;
  } else {
    runs.push({ t: text, ...marks });
  }
}

/**
 * Page-number fields inside headers/footers become the literal tokens of the
 * word model ("{PAGE}", "{NUMPAGES}"); other fields keep their result text.
 */
function fieldToken(instr) {
  const m = /^\s*(PAGE|NUMPAGES|SECTIONPAGES)(?![A-Za-z])/i.exec(instr || "");
  if (!m) return null;
  return m[1].toUpperCase() === "PAGE" ? "{PAGE}" : "{NUMPAGES}";
}

function hyperlinkFromInstr(instr) {
  const m = /^\s*HYPERLINK\s+(?:"([^"]*)"|(\S+))(.*)$/i.exec(instr || "");
  if (!m) return null;
  let url = m[1] !== undefined ? m[1] : m[2];
  const anchor = /\\l\s+"([^"]*)"/.exec(m[3] || "");
  if (anchor) url = (url || "") + "#" + anchor[1];
  return url || null;
}

/**
 * Paragraph-level parse state: runs of the block being built, current link,
 * complex-field stack; images and page breaks split the paragraph.
 */
class ParaState {
  constructor(ctx, makeBlock, out, baseMarks) {
    this.ctx = ctx;
    this.makeBlock = makeBlock;
    this.out = out;
    this.baseMarks = baseMarks;
    this.runs = [];
    this.link = null;
    this.fields = [];
    this.emitted = false;
    this.after = []; // text-box content, emitted after the paragraph
  }
  inInstr() {
    const top = this.fields[this.fields.length - 1];
    return !!top && top.phase === "instr";
  }
  text(t, marks) {
    if (!t || this.inInstr() || this.fields.some((f) => f.suppress)) return;
    const m = { ...marks };
    if (this.link) m.link = this.link;
    pushRunText(this.runs, t, cleanRunMarks(m));
  }
  /** A field token ("{PAGE}"): written even though the field result is suppressed. */
  token(t, marks) {
    const m = { ...marks };
    if (this.link) m.link = this.link;
    pushRunText(this.runs, t, cleanRunMarks(m));
  }
  flush() {
    if (this.runs.length) {
      this.out.push(this.makeBlock(this.runs));
      this.emitted = true;
    }
    this.runs = [];
  }
  block(b) {
    this.flush();
    this.out.push(b);
    this.emitted = true;
  }
  finish() {
    if (this.runs.length || !this.emitted) this.out.push(this.makeBlock(this.runs));
    for (const b of this.after) this.out.push(b);
  }
}

function charStyleMarks(ctx, id) {
  if (!id) return {};
  const st = ctx.styles.styles.get(id);
  const n = (st && st.name) || id.toLowerCase();
  // The Hyperlink character style is presentation of the link itself.
  if (/hyperlink/.test(n) || /hyperlink/i.test(id)) return {};
  return resolveStyle(ctx, id).marks;
}

function chooseAlternate(ac) {
  return kid(ac, "Choice") || kid(ac, "Fallback");
}

function emuToPx(v) {
  const n = parseInt(v || "", 10);
  return n > 0 ? Math.max(1, Math.round(n / 9525)) : 0;
}

function imageBlockFromRel(ctx, rid, alt, w, h) {
  if (!rid) return null;
  const rel = ctx.rels.get(rid);
  if (!rel) return null;
  if (rel.external) {
    ctx.warn("Linked (external) images were not imported.");
    return null;
  }
  const src = ctx.media.get(rid);
  if (!src) {
    ctx.warn("Some images could not be read and were dropped.");
    return null;
  }
  if (/^data:image\/x-(emf|wmf)/.test(src)) ctx.warn("EMF/WMF images cannot be displayed by the browser.");
  const b = { type: "img", src };
  if (alt) b.alt = alt;
  if (w > 0) b.w = w;
  if (h > 0) b.h = h;
  return b;
}

/** DrawingML (w:drawing): pictures become img blocks; text boxes are moved after the paragraph. */
function handleDrawing(node, ctx, st) {
  const docPr = findDesc(node, "docPr");
  const alt = docPr ? attr(docPr, "descr") || attr(docPr, "title") || "" : "";
  const extent = findDesc(node, "extent");
  const pics = findAllDesc(node, "pic");
  let any = false;
  if (pics.length) {
    for (const pic of pics) {
      const blip = findDesc(pic, "blip");
      if (!blip) continue;
      const ext = findDesc(findDesc(pic, "spPr"), "ext");
      const sizeSrc = pics.length === 1 && extent ? extent : ext || extent;
      const b = imageBlockFromRel(ctx, attr(blip, "r:embed") || attr(blip, "r:link"), alt,
        emuToPx(attr(sizeSrc, "cx")), emuToPx(attr(sizeSrc, "cy")));
      if (b) { st.block(b); any = true; }
    }
  } else {
    const blip = findDesc(node, "blip");
    if (blip) {
      const b = imageBlockFromRel(ctx, attr(blip, "r:embed") || attr(blip, "r:link"), alt,
        emuToPx(attr(extent, "cx")), emuToPx(attr(extent, "cy")));
      if (b) { st.block(b); any = true; }
    }
  }
  const tbx = findAllDesc(node, "txbxContent");
  if (tbx.length) {
    ctx.warn("Text box contents were moved into the main text.");
    for (const t of tbx) parseBlockChildren(t, ctx, st.after);
    any = true;
  }
  if (!any) {
    const gd = findDesc(node, "graphicData");
    const uri = (gd && attr(gd, "uri")) || "";
    if (/chart/i.test(uri)) ctx.warn("Charts were not imported.");
    else if (/diagram/i.test(uri)) ctx.warn("SmartArt diagrams were not imported.");
    else ctx.warn("Some drawings or shapes were not imported.");
  }
}

/** VML (w:pict / w:object): v:imagedata pictures and v:textbox content. */
function handleVml(node, ctx, st) {
  let any = false;
  for (const im of findAllDesc(node, "imagedata")) {
    const shape = findShapeFor(node, im);
    const style = (shape && attr(shape, "style")) || "";
    const dim = (prop) => {
      const m = new RegExp(`(?:^|;)\\s*${prop}\\s*:\\s*([\\d.]+)(pt|px|in)?`, "i").exec(style);
      if (!m) return 0;
      const v = parseFloat(m[1]);
      const unit = (m[2] || "px").toLowerCase();
      return Math.round(unit === "pt" ? v * 4 / 3 : unit === "in" ? v * 96 : v);
    };
    const b = imageBlockFromRel(ctx, attr(im, "r:id") || attr(im, "r:pict"), attr(im, "o:title") || "", dim("width"), dim("height"));
    if (b) { st.block(b); any = true; }
  }
  const tbx = findAllDesc(node, "txbxContent");
  if (tbx.length) {
    ctx.warn("Text box contents were moved into the main text.");
    for (const t of tbx) parseBlockChildren(t, ctx, st.after);
    any = true;
  }
  if (!any) ctx.warn(node.local === "object" ? "Embedded objects were not imported." : "Some drawings or shapes were not imported.");
}

function findShapeFor(root, target) {
  // The element (v:shape / v:rect …) that directly contains `target`.
  for (const c of kids(root)) {
    if (c.children.includes(target)) return c;
    const d = findShapeFor(c, target);
    if (d) return d;
  }
  return null;
}

function parseRunEl(r, ctx, st) {
  const direct = rPrMarks(kid(r, "rPr"));
  if (direct.vanish) return;
  const marks = { ...st.baseMarks, ...charStyleMarks(ctx, direct.rStyle), ...direct };
  runChildren(r, ctx, st, marks);
}

function runChildren(r, ctx, st, marks) {
  for (const c of kids(r)) {
    switch (c.local) {
      case "t": st.text(textOf(c), marks); break;
      case "tab": case "ptab": st.text("\t", marks); break;
      case "br": case "cr": {
        const type = attr(c, "type");
        if (type === "page") st.block({ type: "pagebreak" });
        else st.text("\n", marks);
        break;
      }
      case "noBreakHyphen": st.text("‑", marks); break;
      case "sym": {
        const code = parseInt(attr(c, "char") || "", 16);
        if (code > 0) {
          const cp = code >= 0xf000 ? code - 0xf000 : code;
          if (cp >= 0x20) st.text(String.fromCodePoint(cp), marks);
        }
        break;
      }
      case "fldChar": {
        const type = attr(c, "fldCharType");
        if (type === "begin") {
          st.fields.push({ instr: "", phase: "instr", prevLink: st.link, linked: false });
        } else if (type === "separate") {
          const top = st.fields[st.fields.length - 1];
          if (top) {
            top.phase = "result";
            const url = hyperlinkFromInstr(top.instr);
            if (url) { st.link = url; top.linked = true; }
            const tok = ctx.hf ? fieldToken(top.instr) : null;
            if (tok) { st.token(tok, marks); top.suppress = true; }
          }
        } else if (type === "end") {
          const top = st.fields.pop();
          if (top) {
            st.link = top.prevLink;
            // A field without a result part still shows its token.
            const tok = ctx.hf && top.phase === "instr" ? fieldToken(top.instr) : null;
            if (tok) st.token(tok, marks);
          }
        }
        break;
      }
      case "instrText": {
        const top = st.fields[st.fields.length - 1];
        if (top && top.phase === "instr") top.instr += textOf(c);
        break;
      }
      case "drawing": handleDrawing(c, ctx, st); break;
      case "pict": case "object": handleVml(c, ctx, st); break;
      case "AlternateContent": {
        const branch = chooseAlternate(c);
        if (branch) runChildren(branch, ctx, st, marks);
        break;
      }
      case "footnoteReference": case "endnoteReference":
        ctx.warn("Footnotes and endnotes were not imported.");
        break;
      case "ruby": {
        const base = kid(c, "rubyBase");
        if (base) for (const rr of kids(base, "r")) parseRunEl(rr, ctx, st);
        break;
      }
      default: break; // rPr, delText, lastRenderedPageBreak, commentReference, softHyphen…
    }
  }
}

function mathText(node) {
  return findAllDesc(node, "t").map(textOf).join("");
}

function paragraphChildren(node, ctx, st) {
  for (const c of kids(node)) {
    switch (c.local) {
      case "pPr": break;
      case "r": parseRunEl(c, ctx, st); break;
      case "hyperlink": {
        const prev = st.link;
        const rid = attr(c, "r:id");
        const anchor = attr(c, "anchor");
        let url = rid && ctx.rels.get(rid) ? ctx.rels.get(rid).target : null;
        if (anchor) url = (url || "") + "#" + anchor;
        if (url) st.link = url;
        paragraphChildren(c, ctx, st);
        st.link = prev;
        break;
      }
      case "fldSimple": {
        const tok = ctx.hf ? fieldToken(attr(c, "instr")) : null;
        if (tok) {
          const r = findDesc(c, "r");
          st.token(tok, { ...st.baseMarks, ...(r ? rPrMarks(kid(r, "rPr")) : {}) });
          break;
        }
        const prev = st.link;
        const url = hyperlinkFromInstr(attr(c, "instr"));
        if (url) st.link = url;
        paragraphChildren(c, ctx, st);
        st.link = prev;
        break;
      }
      case "ins": case "moveTo":
        ctx.warn("Tracked changes were accepted.");
        paragraphChildren(c, ctx, st);
        break;
      case "del": case "moveFrom":
        ctx.warn("Tracked changes were accepted.");
        break;
      case "smartTag": case "customXml": case "dir": case "bdo":
        paragraphChildren(c, ctx, st);
        break;
      case "sdt": {
        const content = kid(c, "sdtContent");
        if (content) paragraphChildren(content, ctx, st);
        break;
      }
      case "AlternateContent": {
        const branch = chooseAlternate(c);
        if (branch) paragraphChildren(branch, ctx, st);
        break;
      }
      case "oMath": case "oMathPara": {
        const t = mathText(c);
        if (t) {
          ctx.warn("Equations were imported as plain text.");
          st.text(t, st.baseMarks);
        }
        break;
      }
      default: break; // bookmarks, proofErr, permStart, commentRange…
    }
  }
}

const MONO_FONTS = new Set(["consolas", "courier", "courier new", "menlo", "monaco", "lucida console", "source code pro",
  "dejavu sans mono", "liberation mono", "cascadia code", "cascadia mono", "fira code", "monospace", "jetbrains mono",
  "roboto mono", "ubuntu mono", "sf mono"]);
function isMonoFont(f) {
  return !!f && MONO_FONTS.has(String(f).trim().replace(/^["']|["']$/g, "").toLowerCase());
}
/** Font of the paragraph mark (pPr/rPr/rFonts). */
function paragraphMarkFont(pPr) {
  const rf = pPr && kid(kid(pPr, "rPr") || { children: [] }, "rFonts");
  return rf ? attr(rf, "ascii") || attr(rf, "hAnsi") : null;
}
/** Level implied by a legacy literal-marker list indent (left = 360*(level+1), hanging = 360), or null. */
function legacyListIndent(pPr) {
  const ind = pPr && kid(pPr, "ind");
  if (!ind) return null;
  const hanging = parseInt(attr(ind, "hanging"), 10);
  const left = parseInt(attr(ind, "left") || attr(ind, "start"), 10);
  if (hanging !== 360 || !(left >= 360) || left % 360 !== 0) return null;
  return { level: Math.min(8, left / 360 - 1) };
}
/** Strip a literal "    • " / "12. " marker from the first run; returns {list, level, runs} or null. */
function stripLegacyMarker(runs, legacy) {
  const first = runs[0];
  if (!first || typeof first.t !== "string") return null;
  const m = /^((?: {4})*)(• |\d+\. )/.exec(first.t);
  if (!m) return null;
  const rest = first.t.slice(m[0].length);
  const out = rest ? [{ ...first, t: rest }, ...runs.slice(1)] : runs.slice(1);
  return { list: m[2] === "• " ? "ul" : "ol", level: legacy.level, runs: out };
}

function parseParagraphEl(p, ctx, out) {
  const pPr = kid(p, "pPr");
  const styleId = (pPr && attr(kid(pPr, "pStyle"), "val")) || ctx.styles.defaultPara;
  const style = resolveStyle(ctx, styleId);
  const isDefaultStyle = !styleId || styleId === ctx.styles.defaultPara;

  let kind = style.kind || "p";
  const directOutline = pPr && kid(pPr, "outlineLvl") ? parseInt(attr(kid(pPr, "outlineLvl"), "val"), 10) : null;
  if (kind === "p" && directOutline != null && directOutline >= 0 && directOutline <= 5) kind = `h${directOutline + 1}`;

  const numPr = pPr && kid(pPr, "numPr");
  let numId = style.numId;
  let ilvl = style.ilvl || 0;
  if (numPr) {
    if (kid(numPr, "numId")) numId = attr(kid(numPr, "numId"), "val");
    if (kid(numPr, "ilvl")) ilvl = parseInt(attr(kid(numPr, "ilvl"), "val"), 10) || 0;
  }
  ilvl = Math.max(0, Math.min(8, ilvl));
  let list = /^h[1-6]$/.test(kind) ? null : listKindOf(ctx, numId, ilvl);
  if (!list && numId == null && style.listHint && !/^h[1-6]$/.test(kind)) {
    list = style.listHint.list;
    ilvl = style.listHint.level;
  }

  const jc = pPr && kid(pPr, "jc") ? attr(kid(pPr, "jc"), "val") : style.jc;
  const align = alignOfJc(jc);

  const pbb = pPr && kid(pPr, "pageBreakBefore") ? onOff(kid(pPr, "pageBreakBefore")) : style.pageBreakBefore;
  if (pbb) out.push({ type: "pagebreak" });

  // Run properties of a custom paragraph style are real formatting; those of
  // the default style / headings / quotes are implied by the block type.
  const baseMarks = !isDefaultStyle && (kind === "p" || list) ? { ...style.marks } : {};
  delete baseMarks.rStyle;
  delete baseMarks.vanish;

  // Documents written by older versions of this extension's backend carry
  // lists as literal text ("    • " / "1. " + w:ind hanging=360) and code as
  // NoSpacing paragraphs in a monospace font. Recover them like docx.rs does.
  const legacy = !list && numId == null && kind === "p" ? legacyListIndent(pPr) : null;
  if (!list && kind === "p" && /^nospacing$/i.test(styleId || "") && isMonoFont(paragraphMarkFont(pPr))) kind = "code";
  let firstBlock = true;
  const makeBlock = (runs) => {
    if (firstBlock) {
      firstBlock = false;
      const rec = legacy ? stripLegacyMarker(runs, legacy) : null;
      if (rec) return { type: "list", list: rec.list, level: rec.level, runs: rec.runs };
    }
    if (list) return { type: "list", list, level: ilvl, runs };
    const b = { type: kind, runs };
    if (align) b.align = align;
    return b;
  };
  const st = new ParaState(ctx, makeBlock, out, baseMarks);
  paragraphChildren(p, ctx, st);
  st.finish();
}

function rowCells(tr) {
  const out = [];
  for (const c of kids(tr)) {
    if (c.local === "tc") out.push(c);
    else if (c.local === "sdt") {
      const content = kid(c, "sdtContent");
      if (content) out.push(...rowCells(content));
    } else if (c.local === "customXml") out.push(...rowCells(c));
  }
  return out;
}

function tableRowsOf(tbl) {
  const out = [];
  for (const c of kids(tbl)) {
    if (c.local === "tr") out.push(c);
    else if (c.local === "sdt") {
      const content = kid(c, "sdtContent");
      if (content) out.push(...tableRowsOf(content));
    } else if (c.local === "customXml") out.push(...tableRowsOf(c));
  }
  return out;
}

function parseTableEl(tbl, ctx, out) {
  const rows = [];
  for (const tr of tableRowsOf(tbl)) {
    const cells = [];
    for (const tc of rowCells(tr)) {
      const tcPr = kid(tc, "tcPr");
      const span = parseInt(attr(kid(tcPr, "gridSpan"), "val") || "1", 10);
      const vMerge = kid(tcPr, "vMerge");
      const blocks = [];
      parseBlockChildren(tc, ctx, blocks);
      if (vMerge && attr(vMerge, "val") !== "restart" && rows.length) {
        ctx.warn("Vertically merged table cells were split.");
      }
      const cell = { blocks: blocks.length ? blocks : [{ type: "p", runs: [] }] };
      if (span > 1) cell.colspan = Math.min(span, 1000);
      cells.push(cell);
    }
    if (cells.length) rows.push(cells);
  }
  if (rows.length) out.push({ type: "table", rows });
}

function parseBlockChildren(node, ctx, out) {
  for (const c of kids(node)) {
    switch (c.local) {
      case "p": parseParagraphEl(c, ctx, out); break;
      case "tbl": parseTableEl(c, ctx, out); break;
      case "sdt": {
        const content = kid(c, "sdtContent");
        if (content) parseBlockChildren(content, ctx, out);
        break;
      }
      case "customXml": parseBlockChildren(c, ctx, out); break;
      case "ins": case "moveTo": parseBlockChildren(c, ctx, out); break;
      case "AlternateContent": {
        const branch = chooseAlternate(c);
        if (branch) parseBlockChildren(branch, ctx, out);
        break;
      }
      case "altChunk": ctx.warn("Embedded documents (altChunk) were not imported."); break;
      default: break; // sectPr, bookmarks…
    }
  }
}

/**
 * Read a .docx file into the word model.
 * @param {Uint8Array|ArrayBuffer} bytes
 * @returns {Promise<{model: object, warnings: string[]}>}
 */
export async function docxToModel(bytes) {
  const JSZip = getJSZip();
  const data = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  if (data.length >= 4 && data[0] === 0xd0 && data[1] === 0xcf && data[2] === 0x11 && data[3] === 0xe0) {
    throw new Error("This file is password-protected or a legacy binary Word file; it cannot be opened in the browser.");
  }
  let zip;
  try {
    zip = await JSZip.loadAsync(data);
  } catch (e) {
    throw new Error(`Not a valid .docx file (${e && e.message ? e.message : e}).`);
  }
  checkZipLimits(zip);

  const readBytes = async (path) => {
    const f = zip.file(path) || zip.file(Object.keys(zip.files).find((k) => k.toLowerCase() === path.toLowerCase()) || "\u0000");
    return f ? f.async("uint8array") : null;
  };
  const readText = async (path) => {
    const u8 = await readBytes(path);
    return u8 ? decodeXmlBytes(u8) : null;
  };

  // Main document part from the package relationships.
  let mainPath = "word/document.xml";
  const pkgRels = parseRels(await readText("_rels/.rels"));
  for (const rel of pkgRels.values()) {
    if (relType(rel, "officeDocument")) {
      mainPath = resolvePart("", rel.target);
      break;
    }
  }
  const docXml = await readText(mainPath);
  if (docXml == null) throw new Error("Not a Word document: the main document part is missing.");
  const slash = mainPath.lastIndexOf("/");
  const baseDir = slash >= 0 ? mainPath.slice(0, slash + 1) : "";
  const rels = parseRels(await readText(`${baseDir}_rels/${mainPath.slice(slash + 1)}.rels`));

  const partOf = (type, fallback) => {
    for (const rel of rels.values()) if (relType(rel, type) && !rel.external) return resolvePart(baseDir, rel.target);
    return fallback ? baseDir + fallback : null;
  };
  const stylesInfo = parseStyles(await readText(partOf("styles", "styles.xml")));
  const numbering = parseNumbering(await readText(partOf("numbering", "numbering.xml")), stylesInfo);

  const warnings = [];
  const ctx = {
    rels,
    styles: stylesInfo,
    styleCache: new Map(),
    numbering,
    media: new Map(),
    warn(msg) { if (!warnings.includes(msg)) warnings.push(msg); },
  };

  // Load every embedded image up front (the body walk is synchronous).
  for (const [id, rel] of rels) {
    if (!relType(rel, "image") || rel.external) continue;
    const path = resolvePart(baseDir, rel.target);
    const u8 = await readBytes(path);
    if (!u8) continue;
    const ext = (path.split(".").pop() || "").toLowerCase();
    const mime = EXT_MIME[ext] || "application/octet-stream";
    ctx.media.set(id, `data:${mime};base64,${bytesToBase64(u8)}`);
  }

  const doc = parseXml(docXml);
  const body = findDesc(doc, "body");
  const blocks = [];
  if (body) parseBlockChildren(body, ctx, blocks);

  for (const rel of rels.values()) {
    if (relType(rel, "comments")) ctx.warn("Comments were not imported.");
  }

  const model = { kind: "word", meta: {}, blocks };
  // Page setup of the (last) section, in the backend's meta.page shape.
  const sects = body ? kids(body, "sectPr") : [];
  const lastSect = sects.length ? sects[sects.length - 1] : null;
  const page = lastSect ? pageOfSectPr(lastSect) : null;
  if (page) model.meta.page = page;
  // Default header / footer of the last section (page-number fields -> tokens).
  // Header/footer parts the last section does not use (earlier sections) are dropped.
  const usedHf = new Set(lastSect ? [...kids(lastSect, "headerReference"), ...kids(lastSect, "footerReference")].map((r) => attr(r, "r:id")) : []);
  for (const [id, rel] of rels) {
    if ((relType(rel, "header") || relType(rel, "footer")) && !usedHf.has(id)) ctx.warn("Headers and footers were not imported.");
  }
  for (const kind of ["header", "footer"]) {
    const refs = lastSect ? kids(lastSect, `${kind}Reference`) : [];
    const typeOf = (r) => attr(r, "w:type") || "default";
    if (refs.some((r) => typeOf(r) !== "default")) {
      ctx.warn("Only the main header and footer were imported (first-page and even-page versions were dropped).");
    }
    const ref = refs.find((r) => typeOf(r) === "default");
    const rel = ref ? rels.get(attr(ref, "r:id")) : null;
    if (!rel || rel.external) continue;
    const path = resolvePart(baseDir, rel.target);
    const xml = await readText(path);
    if (!xml) continue;
    const ps = path.lastIndexOf("/");
    const hfRels = parseRels(await readText(`${path.slice(0, ps + 1)}_rels/${path.slice(ps + 1)}.rels`));
    const hfBlocks = [];
    const hfRoot = findDesc(parseXml(xml), kind === "header" ? "hdr" : "ftr");
    if (hfRoot) parseBlockChildren(hfRoot, { ...ctx, rels: hfRels, media: new Map(), hf: true }, hfBlocks);
    const hf = headerFooterOf(hfBlocks, ctx);
    if (hf) model.meta[kind] = hf;
  }
  const core = await readText("docProps/core.xml");
  if (core) {
    const croot = parseXml(core);
    for (const [key, local] of [["title", "title"], ["author", "creator"], ["subject", "subject"]]) {
      const v = textOf(findDesc(croot, local)).trim();
      if (v) model.meta[key] = v;
    }
  }
  return { model, warnings };
}

/**
 * Header/footer blocks -> the model's one-paragraph { runs, align }:
 * paragraphs are joined with line breaks, table cells with tabs; pictures
 * are dropped (with a note). Returns null when there is no text.
 */
function headerFooterOf(blocks, ctx) {
  const lines = [];
  let align = null;
  const visit = (list) => {
    for (const b of list) {
      if (!b) continue;
      if (Array.isArray(b.runs)) {
        if (!align && b.align) align = b.align;
        lines.push(b.runs);
      } else if (b.type === "table") {
        for (const row of b.rows || []) {
          const cells = row.map((c) => {
            const sub = [];
            const save = lines.length;
            visit(c.blocks || []);
            for (const r of lines.splice(save)) { if (sub.length) sub.push({ t: " " }); sub.push(...r); }
            return sub;
          });
          const merged = [];
          cells.forEach((c, i) => { if (i) merged.push({ t: "\t" }); merged.push(...c); });
          lines.push(merged);
        }
      } else if (b.type === "img") {
        ctx.warn("Pictures in headers and footers were not imported.");
      }
    }
  };
  visit(blocks);
  while (lines.length && !lines[lines.length - 1].some((r) => r.t && r.t.trim())) lines.pop();
  while (lines.length && !lines[0].some((r) => r.t && r.t.trim())) lines.shift();
  if (!lines.length) return null;
  const runs = [];
  lines.forEach((l, i) => {
    if (i) runs.push({ t: "\n" });
    for (const r of l) if (r && r.t) runs.push({ ...r });
  });
  // Merge neighbours with identical formatting.
  const out = [];
  for (const r of runs) {
    const last = out[out.length - 1];
    if (last && RUN_KEYS.every((k) => (last[k] || undefined) === (r[k] || undefined))) last.t += r.t;
    else out.push(r);
  }
  const hf = { runs: out };
  if (align && align !== "left") hf.align = align;
  return hf;
}

// ---------------------------------------------------------------------------
// Page setup (meta.page, twips) — same shape as the backend's docx.rs:
// { size: "A4"|"Letter"|...|"custom", orientation, width, height,
//   margins: { top, right, bottom, left, header, footer } }
// ---------------------------------------------------------------------------

const PAGE_SIZES = { A4: [11906, 16838], Letter: [12240, 15840], Legal: [12240, 20160], A3: [16838, 23811], A5: [8391, 11906], Executive: [10440, 15120] };
const DEFAULT_MARGINS = { top: 1440, right: 1440, bottom: 1440, left: 1440, header: 720, footer: 720 };

function pageSizeName(w, h) {
  const [a, b] = w <= h ? [w, h] : [h, w];
  for (const [name, [x, y]] of Object.entries(PAGE_SIZES)) if (Math.abs(a - x) <= 60 && Math.abs(b - y) <= 60) return name;
  return "custom";
}

function pageOfSectPr(sectPr) {
  const sz = kid(sectPr, "pgSz");
  const mar = kid(sectPr, "pgMar");
  const num = (el, a) => { const v = parseInt(attr(el, a), 10); return Number.isFinite(v) ? v : null; };
  const w = num(sz, "w"), h = num(sz, "h");
  if (!(w > 0 && h > 0)) return null;
  const margins = {};
  for (const k of Object.keys(DEFAULT_MARGINS)) {
    const v = mar ? num(mar, k) : null;
    margins[k] = v != null ? Math.abs(v) : DEFAULT_MARGINS[k];
  }
  const orient = attr(sz, "orient");
  return { size: pageSizeName(w, h), orientation: orient === "landscape" || (!orient && w > h) ? "landscape" : "portrait", width: w, height: h, margins };
}

/** Resolve meta.page to concrete twips (defaults: US Letter, 1in margins). */
function pageSetupOf(meta) {
  const p = (meta && typeof meta.page === "object" && meta.page) || {};
  let [w, h] = PAGE_SIZES[p.size] || PAGE_SIZES.Letter;
  const inRange = (v, lo, hi) => typeof v === "number" && v >= lo && v <= hi;
  if (inRange(p.width, 1440, 31680) && inRange(p.height, 1440, 31680)) { w = Math.round(p.width); h = Math.round(p.height); }
  if (p.orientation === "landscape" && w < h) [w, h] = [h, w];
  if (p.orientation === "portrait" && w > h) [w, h] = [h, w];
  const m = { ...DEFAULT_MARGINS };
  if (p.margins && typeof p.margins === "object") {
    for (const k of Object.keys(m)) if (inRange(p.margins[k], 0, 14400)) m[k] = Math.round(p.margins[k]);
  }
  // Keep a usable text column even with absurd margins.
  const textWidth = Math.max(1440, w - m.left - m.right);
  return { w, h, landscape: w > h, m, textWidth };
}

