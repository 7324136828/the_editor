function numberingXml(nums) {
  const BULLETS = ["•", "◦", "▪"];
  const FMTS = ["decimal", "lowerLetter", "lowerRoman"];
  const lvl = (i, fmt, text) =>
    `<w:lvl w:ilvl="${i}"><w:start w:val="1"/><w:numFmt w:val="${fmt}"/><w:lvlText w:val="${text}"/><w:lvlJc w:val="left"/>` +
    `<w:pPr><w:ind w:left="${720 * (i + 1)}" w:hanging="360"/></w:pPr></w:lvl>`;
  let x = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:numbering xmlns:w="${NS.w}">`;
  x += '<w:abstractNum w:abstractNumId="0"><w:multiLevelType w:val="hybridMultilevel"/>';
  for (let i = 0; i < 9; i++) x += lvl(i, "bullet", BULLETS[i % 3]);
  x += "</w:abstractNum>";
  x += '<w:abstractNum w:abstractNumId="1"><w:multiLevelType w:val="hybridMultilevel"/>';
  for (let i = 0; i < 9; i++) x += lvl(i, FMTS[i % 3], `%${i + 1}.`);
  x += "</w:abstractNum>";
  x += '<w:num w:numId="1"><w:abstractNumId w:val="0"/></w:num>';
  for (const n of nums) {
    x += `<w:num w:numId="${n.numId}"><w:abstractNumId w:val="1"/>` +
      `<w:lvlOverride w:ilvl="${n.level}"><w:startOverride w:val="1"/></w:lvlOverride></w:num>`;
  }
  return x + "</w:numbering>";
}

